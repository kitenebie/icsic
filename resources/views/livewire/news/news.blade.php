<script>
    // News Image Preview Functions
    let currentNewsImages = [];
    let currentNewsImageIndex = 0;

    window.openNewsImagePreview = function(images, startIndex = 0) {
        currentNewsImages = images;
        currentNewsImageIndex = startIndex;
        updateNewsImagePreview();
        document.getElementById('newsImagePreviewModal').classList.remove('hidden');
    };

    window.closeNewsImagePreview = function() {
        document.getElementById('newsImagePreviewModal').classList.add('hidden');
    };

    window.changeNewsImage = function(direction) {
        currentNewsImageIndex = (currentNewsImageIndex + direction + currentNewsImages.length) % currentNewsImages.length;
        updateNewsImagePreview();
    };

    function updateNewsImagePreview() {
        const previewImage = document.getElementById('newsPreviewImage');
        const currentIndex = document.getElementById('newsCurrentImageIndex');
        const totalImages = document.getElementById('newsTotalImages');
        const prevBtn = document.getElementById('prevNewsImageBtn');
        const nextBtn = document.getElementById('nextNewsImageBtn');

        previewImage.src = `/storage/${currentNewsImages[currentNewsImageIndex]}`;
        currentIndex.textContent = currentNewsImageIndex + 1;
        totalImages.textContent = currentNewsImages.length;

        // Update navigation buttons
        prevBtn.style.display = currentNewsImages.length > 1 ? 'block' : 'none';
        nextBtn.style.display = currentNewsImages.length > 1 ? 'block' : 'none';
    }

    // Keyboard navigation for news image preview
    document.addEventListener('keydown', function(e) {
        if (document.getElementById('newsImagePreviewModal').classList.contains('hidden')) return;

        if (e.key === 'ArrowLeft') {
            changeNewsImage(-1);
        } else if (e.key === 'ArrowRight') {
            changeNewsImage(1);
        } else if (e.key === 'Escape') {
            closeNewsImagePreview();
        }
    });
</script>
